/**
 * Comentário de documentação (Javadoc): descreve a classe.
 * Ferramentas como o javadoc geram páginas HTML a partir dele.
 */
public class Comentarios {

    /** Ponto de entrada do programa. */
    public static void main(String[] args) {
        // Comentário de uma linha: vai até o fim da linha.
        System.out.println("Comentários não aparecem na saída.");

        /*
         * Comentário de várias linhas:
         * útil para explicar um trecho maior.
         */
        System.out.println("Mas ajudam quem lê o código!"); // pode vir no fim da linha
    }
}
