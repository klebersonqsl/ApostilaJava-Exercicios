CREATE TABLE produto (
    id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome     VARCHAR(80) NOT NULL,
    preco    DECIMAL(10,2) NOT NULL,
    cadastro DATE NOT NULL);
