/** As diferenças de SQL entre os bancos ficam concentradas aqui. */
public enum Banco {

    SQLITE("""
            CREATE TABLE produto (
                id       INTEGER PRIMARY KEY AUTOINCREMENT,
                nome     VARCHAR(80) NOT NULL,
                preco    DECIMAL(10,2) NOT NULL,
                cadastro DATE NOT NULL)"""),

    POSTGRESQL("""
            CREATE TABLE produto (
                id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                nome     VARCHAR(80) NOT NULL,
                preco    DECIMAL(10,2) NOT NULL,
                cadastro DATE NOT NULL)"""),

    MYSQL("""
            CREATE TABLE produto (
                id       INT AUTO_INCREMENT PRIMARY KEY,
                nome     VARCHAR(80) NOT NULL,
                preco    DECIMAL(10,2) NOT NULL,
                cadastro DATE NOT NULL)"""),

    FIREBIRD("""
            CREATE TABLE produto (
                id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                nome     VARCHAR(80) NOT NULL,
                preco    DECIMAL(10,2) NOT NULL,
                cadastro DATE NOT NULL)"""),

    SQLSERVER("""
            CREATE TABLE produto (
                id       INT IDENTITY(1,1) PRIMARY KEY,
                nome     NVARCHAR(80) NOT NULL,
                preco    DECIMAL(10,2) NOT NULL,
                cadastro DATE NOT NULL)""");

    private final String criarTabela;

    Banco(String criarTabela) {
        this.criarTabela = criarTabela;
    }

    public String criarTabela() {
        return criarTabela;
    }

    /** Comando que apaga a tabela se ela existir. */
    public String apagarTabela(String tabela) {
        return this == FIREBIRD
                ? "EXECUTE BLOCK AS BEGIN IF (EXISTS(SELECT 1 FROM RDB$RELATIONS "
                  + "WHERE RDB$RELATION_NAME = '" + tabela.toUpperCase() + "')) THEN "
                  + "EXECUTE STATEMENT 'DROP TABLE " + tabela + "'; END"
                : "DROP TABLE IF EXISTS " + tabela;
    }

    /** Acrescenta a paginação ao SELECT (que já deve ter ORDER BY). */
    public String paginar(String select, int limite, int deslocamento) {
        return switch (this) {
            case SQLITE, MYSQL -> select + " LIMIT " + limite + " OFFSET " + deslocamento;
            case POSTGRESQL, FIREBIRD, SQLSERVER ->
                    select + " OFFSET " + deslocamento + " ROWS FETCH NEXT " + limite
                            + " ROWS ONLY";
        };
    }

    /** Tipo de coluna para dados binários (imagens, PDFs...). */
    public String tipoBinario() {
        return switch (this) {
            case SQLITE -> "BLOB";
            case POSTGRESQL -> "BYTEA";
            case MYSQL -> "LONGBLOB";
            case FIREBIRD -> "BLOB SUB_TYPE BINARY";
            case SQLSERVER -> "VARBINARY(MAX)";
        };
    }

    /** O driver do SQLite não implementa getGeneratedKeys: usa-se RETURNING. */
    public boolean usaReturning() {
        return this == SQLITE;
    }

    public static Banco daUrl(String url) {
        if (url.startsWith("jdbc:sqlite")) return SQLITE;
        if (url.startsWith("jdbc:postgresql")) return POSTGRESQL;
        if (url.startsWith("jdbc:mysql") || url.startsWith("jdbc:mariadb")) return MYSQL;
        if (url.startsWith("jdbc:firebird")) return FIREBIRD;
        if (url.startsWith("jdbc:sqlserver")) return SQLSERVER;
        throw new IllegalArgumentException("Banco não suportado: " + url);
    }
}
